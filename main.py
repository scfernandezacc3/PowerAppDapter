import csv
from difflib import SequenceMatcher
import requests


def calculate_match_score(query_term: str, title: str, snippet: str) -> float:
    """Calculates a heuristic match quality score between 0.0 and 1.0.

    Parameters:
        query_term (str): The search identifier (e.g., email or phone number).
        title (str): The web page title returned by the search engine.
        snippet (str): The text snippet/preview returned by the search engine.

    Returns:
        float: A normalized confidence score from 0.0 (no match) to 1.0 (exact
        match).
    """
    # Standardize input strings to lowercase for case-insensitive comparison
    query_clean = query_term.strip().lower()
    combined_text = f"{title} {snippet}".lower()

    # Priority 1: Exact substring match in either title or snippet indicates highest confidence
    if query_clean in combined_text:
        return 1.0

    # Priority 2: Fuzzy matching for partial/similar occurrences (e.g., slight formatting variations)
    words = combined_text.split()
    query_words = query_clean.split()
    query_len = len(query_words)

    # Return 0.0 if the returned snippet contains fewer words than the query term itself
    if len(words) < query_len:
        return 0.0

    max_similarity = 0.0

    # Slide a fixed-length window across the result text to compare against the query string
    for i in range(len(words) - query_len + 1):
        chunk = " ".join(words[i : i + query_len])
        # SequenceMatcher calculates Gestalt pattern matching ratio between two strings
        similarity = SequenceMatcher(None, query_clean, chunk).ratio()
        if similarity > max_similarity:
            max_similarity = similarity

    # Round score to two decimal places for readability
    return round(max_similarity, 2)


def query_search_api(
    api_key: str, search_engine_id: str, query_term: str
) -> list[dict]:
    """Queries the Google Custom Search JSON API for a given search term and

    scores the results based on relevance.

    Parameters:
        api_key (str): Official Google API key.
        search_engine_id (str): Google Custom Search Engine ID (cx).
        query_term (str): Identifier to query against the search engine.

    Returns:
        list[dict]: List of dictionaries containing title, link, snippet, and
        match_score.
    """
    url = "https://www.googleapis.com/customsearch/v1"

    # Enclose the query term in double quotes to instruct the engine to search exact phrases
    params = {
        "key": api_key,
        "cx": search_engine_id,
        "q": f'"{query_term}"',
    }

    try:
        # Perform HTTP GET request with a 10-second timeout to prevent hanging requests
        response = requests.get(url, params=params, timeout=10)
        response.raise_for_status()  # Raise HTTPError for 4xx/5xx status codes
        data = response.json()

        results = []
        # Parse items array from API JSON payload (defaults to empty list if key missing)
        for item in data.get("items", []):
            title = item.get("title", "")
            link = item.get("link", "")
            snippet = item.get("snippet", "")

            # Compute match score based on similarity
            score = calculate_match_score(query_term, title, snippet)

            results.append(
                {
                    "query_term": query_term,
                    "title": title,
                    "link": link,
                    "snippet": snippet,
                    "match_score": score,
                }
            )

        # Sort search results in-place in descending order of match_score
        results.sort(key=lambda x: x["match_score"], reverse=True)
        return results

    except requests.exceptions.RequestException as e:
        print(f"[!] Error querying API for term '{query_term}': {e}")
        return []


def export_results_to_csv(results: list[dict], output_file: str) -> None:
    """Writes a list of search result dictionaries to a CSV file.

    Parameters:
        results (list[dict]): Search results generated by query_search_api.
        output_file (str): Destination file path (e.g., 'search_results.csv').
    """
    if not results:
        print("[!] No results to export.")
        return

    # Column headers matching dictionary keys
    fieldnames = ["query_term", "match_score", "title", "link", "snippet"]

    try:
        # Open file with UTF-8 encoding to support international characters and symbols
        with open(output_file, mode="w", newline="", encoding="utf-8") as csvfile:
            writer = csv.DictWriter(csvfile, fieldnames=fieldnames)

            # Write header row
            writer.writeheader()

            # Write individual result rows
            for row in results:
                writer.writerow(row)

        print(
            f"[+] Successfully exported {len(results)} record(s) to '{output_file}'."
        )

    except IOError as e:
        print(f"[!] File write error: {e}")


